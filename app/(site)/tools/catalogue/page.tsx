import type { Metadata } from "next";

import { Illustration } from "@/components/Illustration";
import { PrintButton } from "@/components/tools/PrintButton";
import { ToolHeader } from "@/components/tools/ToolHeader";
import { formatPrice, getCollections, getProducts } from "@/lib/catalogue";
import { DEMO } from "@/lib/site";

export const metadata: Metadata = { title: "Printable catalogue" };

export default async function CataloguePage() {
  const [products, collections] = await Promise.all([getProducts(), getCollections()]);
  const built = new Date().toLocaleDateString("en-MY", { month: "long", year: "numeric" });

  return (
    <div className="mx-auto max-w-[1000px] px-4 py-10 md:py-14 print:max-w-none print:p-0">
      <div className="print:hidden">
        <ToolHeader
          title="Printable catalogue"
          intro="A print-ready product catalogue built straight from the website's products, so the PDF you email customers is never out of date."
          saves="hours of updating a Word or Canva catalogue every time a price or product changes."
          context="printable catalogue tool"
        />
        <div className="mb-8 flex flex-wrap items-center gap-4">
          <PrintButton />
          <p className="text-sm text-steel">Tip: choose &ldquo;Save as PDF&rdquo; as the printer to get a PDF file.</p>
        </div>
      </div>

      {/* Catalogue document */}
      <div className="rounded-xl border border-rule print:rounded-none print:border-0">
        {/* Cover */}
        <section className="relative flex min-h-[420px] flex-col justify-between overflow-hidden bg-char p-10 text-white print:min-h-[95vh] print:break-after-page">
          <div className="hazard absolute inset-x-0 top-0 h-2" aria-hidden />
          <p className="flex items-center gap-3 text-2xl font-black">
            <span className="grid h-12 w-12 place-items-center rounded-md bg-hivis text-char">DH</span>
            {DEMO.name}
          </p>
          <div>
            <p className="font-mono text-sm uppercase tracking-widest text-hivis">Product catalogue · {built}</p>
            <h2 className="mt-3 text-5xl leading-none font-black tracking-tight md:text-6xl">
              {products.length} products.
              <br />
              One list.
            </h2>
            <ul className="mt-6 flex flex-wrap gap-2 text-sm">
              {collections.map((c) => (
                <li key={c.slug} className="rounded-full border border-white/25 px-3 py-1">
                  {c.title} · {c.count}
                </li>
              ))}
            </ul>
          </div>
          <p className="text-xs text-white/60">
            Demo catalogue generated by githzweb from the live website. Fictional company: products and prices are made
            up. Prices in RM, excluding SST.
          </p>
        </section>

        {collections.map((c) => {
          const items = products.filter((p) => p.collection.slug === c.slug);
          return (
            <section key={c.slug} className="p-8 print:break-before-page print:p-0 print:pt-4">
              <header className="flex items-center gap-4 border-b-4 border-char pb-3">
                <Illustration name={c.icon} className="h-12 w-12" />
                <div>
                  <h2 className="text-2xl font-black tracking-tight">{c.title}</h2>
                  <p className="text-sm text-steel">{c.description}</p>
                </div>
              </header>
              <table className="mt-4 w-full text-[13px] print:text-[11px]">
                <thead>
                  <tr className="border-b border-char text-left">
                    <th className="py-2 pr-3">Model</th>
                    <th className="py-2 pr-3">Product</th>
                    <th className="py-2 pr-3">Sizes / options</th>
                    <th className="py-2 pr-3">Per</th>
                    <th className="py-2 text-right">Price</th>
                  </tr>
                </thead>
                <tbody>
                  {items.map((p) => (
                    <tr key={p._id} className="border-b border-rule align-top break-inside-avoid">
                      <td className="py-2 pr-3 font-mono whitespace-nowrap">{p.model}</td>
                      <td className="py-2 pr-3">
                        <span className="font-semibold">{p.name}</span>
                        <span className="block text-steel">{p.brand?.name}</span>
                      </td>
                      <td className="py-2 pr-3 text-steel">{p.variants.map((v) => v.label).join(", ") || "–"}</td>
                      <td className="py-2 pr-3 whitespace-nowrap text-steel">{p.unit}</td>
                      <td className="py-2 text-right font-semibold whitespace-nowrap">{formatPrice(p) ?? "On request"}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </section>
          );
        })}
      </div>
    </div>
  );
}
